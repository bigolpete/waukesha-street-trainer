// Writes data/districts.js with GUESSED first-due areas: a Central circle around
// downtown plus North / East / South / West wedges. Replace data/districts.js with
// the real running areas when available (same format: name, color, rings of [lat, lon]).
//
//   node tools/make-guess-districts.mjs
import { writeFileSync } from "node:fs";

const HUB = [43.0118, -88.2316]; // downtown (Main St / Broadway area)
const CENTRAL_KM = 1.7;
const OUTER_KM = 14; // far past the city limits; the city mask hides the excess

const KM_LAT = 111.32;
const KM_LON = 111.32 * Math.cos((HUB[0] * Math.PI) / 180);
const r5 = (n) => Math.round(n * 1e5) / 1e5;
const pt = (km, bearingDeg) => {
  const b = (bearingDeg * Math.PI) / 180;
  return [r5(HUB[0] + (km * Math.cos(b)) / KM_LAT), r5(HUB[1] + (km * Math.sin(b)) / KM_LON)];
};
const arc = (km, from, to, step = 5) => {
  const out = [];
  for (let a = from; a <= to + 1e-9; a += step) out.push(pt(km, a));
  return out;
};
const wedge = (from, to) => [...arc(CENTRAL_KM, from, to), ...arc(OUTER_KM, from, to).reverse()];

const districts = [
  { name: "Central", color: "#d62728", rings: [arc(CENTRAL_KM, 0, 355)] },
  { name: "North", color: "#1f77b4", rings: [wedge(-45, 45)] },
  { name: "East", color: "#2ca02c", rings: [wedge(45, 135)] },
  { name: "South", color: "#ff7f0e", rings: [wedge(135, 225)] },
  { name: "West", color: "#9467bd", rings: [wedge(225, 315)] },
];

writeFileSync(
  "data/districts.js",
  "// Station running areas. THESE ARE PLACEHOLDER GUESSES (generated by tools/make-guess-districts.mjs).\n" +
    "// Replace with real first-due polygons: each district has a name, a color and rings of [lat, lon].\n" +
    "window.DISTRICTS = " + JSON.stringify(districts, null, 1) + ";\n"
);
console.log("wrote data/districts.js");
